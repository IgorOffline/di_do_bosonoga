inline std::uint32_t key_code(const char *name) {
  for (const auto &key : key_names) {
    if (std::strcmp(name, key.name) == 0) return key.code;
  }
  return 0;
}
inline const char *key_name(std::uint32_t code) {
  for (const auto &key : key_names) {
    if (code == key.code) return key.name;
  }
  return "?";
}
